test('operações administrativas recusam requisições de visitante e cidadão', async ({ page, request, playwright }) => {
  await signIn(page)
  await page.getByRole('button', { name: 'Publicações', exact: true }).click()
  await page.getByLabel('Título', { exact: true }).fill('Publicação para testar permissão')
  await page.getByLabel('Resumo', { exact: true }).fill('Teste de autorização das operações do painel.')
  await page.getByLabel('Conteúdo', { exact: true }).fill('Este registro permite verificar que cidadãos não podem executar ações administrativas.')
  const action = page.waitForRequest(req => req.method() === 'POST' && Boolean(req.headers()['next-action']))
  await page.getByRole('button', { name: 'Salvar como rascunho' }).click()
  const captured = await action
  await expect(page.getByRole('heading', { name: 'Publicação para testar permissão' })).toHaveCount(1)
  const options = { headers: { 'Next-Action': captured.headers()['next-action'], 'Content-Type': captured.headers()['content-type'], Origin: 'http://localhost:3100' }, data: captured.postDataBuffer()! }
  const anonymous = await request.post('/ADM', options)
  expect(anonymous.status()).toBeGreaterThanOrEqual(400)
  expect(await anonymous.text()).toContain('Acesso não autorizado')
  const citizenRequest = await playwright.request.newContext({ baseURL: 'http://localhost:3100' })
  await citizenRequest.post('/api/auth/sign-in/email', { data: { email: citizen, password }, headers: { Origin: 'http://localhost:3100' } })
  const denied = await citizenRequest.post('/ADM', options)
  expect(denied.status()).toBeGreaterThanOrEqual(400)
  expect(await denied.text()).toContain('Acesso não autorizado')
  await page.reload()
  await page.getByRole('button', { name: 'Publicações', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Publicação para testar permissão' })).toHaveCount(1)
  await citizenRequest.dispose()
})

