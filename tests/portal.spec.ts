import { test, expect, type Page } from '@playwright/test'

const password = 'Test-only-Citizen-2026!'
const stamp = 'local-presentation'
const citizen = `citizen-${stamp}@ferroviva.test`

test.beforeAll(async ({ playwright }) => {
  const request = await playwright.request.newContext({ baseURL: 'http://localhost:3100' })
  const response = await request.post('/api/auth/sign-up/email', { data: { name: 'Cidadã de teste', email: citizen, password }, headers: { Origin: 'http://localhost:3100' } })
  expect([200, 422]).toContain(response.status())
  await request.dispose()
})

async function signIn(page: Page, email = 'iarlemlacerda@gmail.com', secret = '12345678', admin = true) {
  await page.goto(admin ? '/ADM' : '/usuarios')
  await page.getByLabel('E-mail', { exact: true }).fill(email)
  await page.getByLabel('Senha', { exact: true }).fill(secret)
  for (let attempt = 0; attempt < 3; attempt++) {
    const response = page.waitForResponse(result => result.url().endsWith('/api/auth/sign-in/email'))
    await page.getByRole('button', { name: 'Entrar', exact: true }).click()
    const result = await response
    if (result.status() !== 429) {
      expect(result.status()).toBe(200)
      break
    }
    await page.waitForTimeout((Number(result.headers()['x-retry-after'] || 10) + 1) * 1000)
  }
  await expect(page).toHaveURL(admin ? /\/ADM$/ : /\/conta$/)
  await expect(page.getByRole('heading', { name: /^Olá,/ })).toBeVisible()
}

test('cadastro público persiste cidadão, rejeita promoção e protege a administração', async ({ page, request }) => {
  const citizen = 'new-citizen@ferroviva.test'
  await page.goto('/cadastro')
  await page.getByLabel('Nome completo').fill('Cidadã de teste')
  await page.getByLabel('E-mail', { exact: true }).fill(citizen)
  await page.getByLabel('Senha', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Criar minha conta' }).click()
  await expect(page).toHaveURL(/\/conta$/)
  await expect(page.getByText(citizen, { exact: true })).toBeVisible()
  await page.goto('/ADM')
  await expect(page).toHaveURL(/\/conta$/)
  await page.getByRole('button', { name: 'Sair da conta' }).click()
  await signIn(page, citizen, password, false)
  await page.reload()
  await expect(page.getByText(citizen, { exact: true })).toBeVisible()

  const response = await request.post('/api/auth/sign-up/email', { data: { name: 'Tentativa de promoção', email: `role-${stamp}@ferroviva.test`, password, role: 'admin' }, headers: { Origin: 'http://localhost:3100' } })
  expect(response.ok()).toBeTruthy()
  const session = await request.get('/api/auth/get-session')
  expect((await session.json()).user.role).toBe('citizen')
  const blocked = await page.request.get('/ADM', { maxRedirects: 0 })
  expect(blocked.status()).toBe(307)
  expect(blocked.headers().location).toBe('/conta')
})

